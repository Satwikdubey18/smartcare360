#!/usr/bin/env python3
"""
SmartCare 360 – Web Embedding Tool
===================================
Reads web/index.html, inlines all CSS and JS files,
and writes the result as a C header file for the ESP32.

Usage:
    python tools/embed_web.py

Output:
    firmware/SmartCare360/dashboard_html.h

The generated header contains a single PROGMEM string
(DASHBOARD_HTML) that the ESP32 serves at http://192.168.4.1

The file must be under 100 KB to fit comfortably in ESP32 flash.
"""

import os
import re
import sys

# --- Paths (relative to repo root) ---
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
WEB_DIR = os.path.join(REPO_ROOT, "web")
HTML_PATH = os.path.join(WEB_DIR, "index.html")
OUTPUT_PATH = os.path.join(REPO_ROOT, "firmware", "SmartCare360", "dashboard_html.h")


def read_file(path):
    """Read a file and return its contents as a string."""
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def inline_css(html, web_dir):
    """Replace <link rel="stylesheet" href="..."> with inline <style>."""
    def replacer(match):
        href = match.group(1)
        css_path = os.path.join(web_dir, href.replace("/", os.sep))
        if os.path.exists(css_path):
            css = read_file(css_path)
            return f"<style>\n{css}\n</style>"
        else:
            print(f"  WARNING: CSS file not found: {css_path}")
            return match.group(0)

    # Match <link rel="stylesheet" href="...">
    pattern = r'<link\s+rel="stylesheet"\s+href="([^"]+)"[^>]*>'
    return re.sub(pattern, replacer, html)


def inline_js(html, web_dir):
    """Replace <script src="..."></script> with inline <script>."""
    def replacer(match):
        src = match.group(1)
        js_path = os.path.join(web_dir, src.replace("/", os.sep))
        if os.path.exists(js_path):
            js = read_file(js_path)
            return f"<script>\n{js}\n</script>"
        else:
            print(f"  WARNING: JS file not found: {js_path}")
            return match.group(0)

    # Match all local <script src="..."></script> tags (excludes http:// CDN scripts)
    pattern = r'<script\s+src="([^"http][^"]*)"[^>]*></script>'
    return re.sub(pattern, replacer, html)


def remove_sw_registration(html):
    """Remove the service worker registration script (not needed offline)."""
    # Remove the inline script that registers the service worker
    pattern = r'<script>\s*if\s*\(\s*"serviceWorker"\s+in\s+navigator\s*\).*?</script>'
    return re.sub(pattern, "", html, flags=re.DOTALL)


def remove_manifest_link(html):
    """Remove the manifest link (not needed when served from ESP32)."""
    pattern = r'<link\s+rel="manifest"[^>]*>'
    return re.sub(pattern, "", html)


def minify_html(html):
    """Light minification — remove extra whitespace but keep readability."""
    # Collapse multiple blank lines to one
    html = re.sub(r'\n\s*\n\s*\n', '\n\n', html)
    # Remove HTML comments (but keep IE conditionals)
    html = re.sub(r'<!--(?!\[).*?-->', '', html, flags=re.DOTALL)
    return html.strip()


def escape_for_c(text):
    """Escape a string for embedding in a C string literal."""
    text = text.replace("\\", "\\\\")
    text = text.replace('"', '\\"')
    text = text.replace("\r", "")
    # Split into lines for readability
    lines = text.split("\n")
    escaped = []
    for line in lines:
        escaped.append('"' + line + '\\n"')
    return "\n".join(escaped)


def generate_header(html_content):
    """Generate the C header file content."""
    escaped = escape_for_c(html_content)
    return f"""// ============================================================
// SmartCare 360 – Embedded Dashboard HTML
// ============================================================
// AUTO-GENERATED by tools/embed_web.py
// Do NOT edit this file manually.
// ============================================================

#ifndef DASHBOARD_HTML_H
#define DASHBOARD_HTML_H

#include <pgmspace.h>

static const char DASHBOARD_HTML[] PROGMEM =
{escaped};

#endif // DASHBOARD_HTML_H
"""


def main():
    print("SmartCare 360 – Web Embedding Tool")
    print("=" * 40)

    # Check input file exists
    if not os.path.exists(HTML_PATH):
        print(f"ERROR: {HTML_PATH} not found!")
        sys.exit(1)

    # Read the HTML
    print(f"Reading: {HTML_PATH}")
    html = read_file(HTML_PATH)
    original_size = len(html.encode("utf-8"))
    print(f"  Original HTML size: {original_size:,} bytes")

    # Inline CSS
    print("Inlining CSS...")
    html = inline_css(html, WEB_DIR)

    # Inline JS
    print("Inlining JS...")
    html = inline_js(html, WEB_DIR)

    # Remove service worker registration and manifest
    print("Removing SW registration and manifest link...")
    html = remove_sw_registration(html)
    html = remove_manifest_link(html)

    # Light minification
    print("Minifying...")
    html = minify_html(html)

    inlined_size = len(html.encode("utf-8"))
    print(f"  Inlined HTML size: {inlined_size:,} bytes")

    # Check size limit
    if inlined_size > 100 * 1024:
        print(f"WARNING: Inlined HTML is {inlined_size:,} bytes (> 100 KB)!")
        print("The ESP32 may not have enough flash. Consider reducing content.")

    # Generate C header
    print("Generating C header...")
    header = generate_header(html)
    header_size = len(header.encode("utf-8"))
    print(f"  Header file size: {header_size:,} bytes")

    if header_size > 100 * 1024:
        print(f"WARNING: Header file is {header_size:,} bytes (> 100 KB)!")
    else:
        print(f"  OK: Under 100 KB limit.")

    # Write output
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(header)

    print(f"Written: {OUTPUT_PATH}")
    print("Done!")
    return 0


if __name__ == "__main__":
    sys.exit(main())

